// fontgen writes font_metrics.go: the advance widths and line metrics of the
// device's Bort fonts, read from the SDK simulator.jar, so the server can lay
// text out the way the phone will draw it. Only metrics are emitted, never
// glyph bitmaps.
//
// Usage: go run ./fontgen <simulator.jar> > font_metrics.go
package main

import (
	"archive/zip"
	"bytes"
	"fmt"
	"go/format"
	"io"
	"log"
	"os"
	"strings"
)

// The order of danger.kimba.KFontMgr.sFontNames (the KBC font IDs) up to the
// last Bort face.
var fontNames = []string{
	"Bort7", "BortBold7", "BortItalic7", "Bort9", "BortBold9", "BortItalic9",
	"Bort12", "BortBold12", "BortItalic12", "BortBoldItalic12", "BortBoldItalic7", "BortBoldItalic9",
}

// metricsRunes is the range of code points tabulated; others use the
// replacement glyph's width.
const metricsRunes = 0x250

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: fontgen <simulator.jar>")
	}
	zr, err := zip.OpenReader(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	defer zr.Close()

	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by fontgen from simulator.jar; DO NOT EDIT.\n\npackage kimba\n\n")
	fmt.Fprintf(&out, "var fontMetricsTable = [...]fontMetrics{\n")
	for id, name := range fontNames {
		data, err := readFile(&zr.Reader, "fonts/"+name+".font")
		if err != nil {
			log.Fatalf("%s: %v", name, err)
		}
		f, err := parseFont(data)
		if err != nil {
			log.Fatalf("%s: %v", name, err)
		}
		fallback := f.width(0xFFFD)
		if fallback < 0 {
			fallback = f.width('?')
		}
		var w []string
		for r := range metricsRunes {
			cw := f.width(rune(r))
			switch {
			case r == '\t' || r == 0xA0:
				cw = f.width(' ')
			case cw < 0:
				cw = fallback
			}
			w = append(w, fmt.Sprint(cw))
		}
		fmt.Fprintf(&out, "\t%d: { // %s\n\t\tascent: %d, descent: %d, fallback: %d,\n\t\twidths: [%d]uint8{%s},\n\t},\n",
			id, name, f.ascent, f.descent, fallback, metricsRunes, wrap(w))
	}
	fmt.Fprintf(&out, "}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	os.Stdout.Write(src)
}

func readFile(zr *zip.Reader, name string) ([]byte, error) {
	f, err := zr.Open(name)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	return io.ReadAll(f)
}

// font is a version-1 "FFSS" device font (danger.ui.DeviceFont1).
type font struct {
	data                 []byte
	ascent, descent, gap int
}

func parseFont(data []byte) (*font, error) {
	if len(data) < 10 || string(data[:4]) != "FFSS" || data[4] != 1 {
		return nil, fmt.Errorf("not a version 1 FFSS font")
	}
	return &font{data: data, ascent: int(int8(data[5])), descent: int(int8(data[6])), gap: int(int8(data[7]))}, nil
}

// u16 reads the little-endian 16-bit word at word index i.
func (f *font) u16(i int) int {
	return int(f.data[2*i]) | int(f.data[2*i+1])<<8
}

// width is DeviceFont1.directCharWidth: the glyph's width plus the gap, or
// -1 when the font has no glyph for r.
func (f *font) width(r rune) int {
	i := 5
	for n := f.u16(4); n > 0; n-- {
		first, last := f.u16(i), f.u16(i+1)
		if int(r) < first {
			return -1
		}
		if int(r) > last {
			i += 3
			continue
		}
		table := i + f.u16(i+2)/2
		glyph := table*2 + f.u16(table+int(r)-first)
		if glyph == 0 {
			return -1
		}
		return int(int8(f.data[glyph])) + f.gap
	}
	return -1
}

func wrap(vals []string) string {
	var b strings.Builder
	for i, v := range vals {
		if i%32 == 0 {
			b.WriteString("\n\t\t\t")
		}
		b.WriteString(v)
		b.WriteString(", ")
	}
	b.WriteString("\n\t\t")
	return b.String()
}
